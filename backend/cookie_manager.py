import os
import tempfile
import time
import logging
from typing import List, Dict, Any
from pathlib import Path

logger = logging.getLogger("vidgrab.cookie_manager")

def write_cookies_to_netscape_format(cookies: List[Dict[str, Any]], temp_dir: Path) -> str:
    """
    Writes a list of Chrome/Firefox style cookies to a temporary file
    in Netscape cookie jar format. Returns the absolute file path,
    or None if the cookie list is empty.
    """
    if not cookies:
        return None

    # Create a temporary file that won't be deleted automatically on close,
    # so yt-dlp can read it. The caller must clean it up after download.
    temp_file = tempfile.NamedTemporaryFile(
        mode='w', encoding='utf-8', delete=False, dir=temp_dir,
        suffix='.txt', prefix='vidgrab_cookies_',
    )
    
    try:
        temp_file.write("# Netscape HTTP Cookie File\n")
        temp_file.write("# This file is generated by VidGrab. Do not edit.\n\n")
        
        for cookie in cookies:
            domain = cookie.get("domain", "")
            path = cookie.get("path", "/")
            secure = "TRUE" if cookie.get("secure", False) else "FALSE"
            
            # Subdomains flag: TRUE if domain starts with a dot
            subdomains = "TRUE" if domain.startswith(".") else "FALSE"
            
            # Expiration
            expiration = cookie.get("expirationDate")
            if expiration is None:
                # 30 days fallback for session cookies
                expiration = int(time.time() + 86400 * 30)
            else:
                expiration = int(expiration)
                
            name = cookie.get("name", "")
            value = cookie.get("value", "")
            
            # Write tab-separated line
            line = f"{domain}\t{subdomains}\t{path}\t{secure}\t{expiration}\t{name}\t{value}\n"
            temp_file.write(line)
            
        temp_file.close()
        logger.info(f"Successfully wrote {len(cookies)} cookies to temp file: {temp_file.name}")
        return temp_file.name
    except Exception as e:
        # Clean up on failure
        try:
            os.unlink(temp_file.name)
        except Exception:
            pass
        logger.error(f"Failed to write Netscape cookies: {e}")
        raise e
