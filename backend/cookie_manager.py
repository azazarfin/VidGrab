"""Private Netscape files whose durable ownership precedes every secret write."""

import ctypes
from ctypes import wintypes
import json
import logging
import math
import os
from pathlib import Path
import stat
import sys
import time
from uuid import UUID, uuid4

from backend.runtime import OutputPathError
from backend.services.artifacts import is_link, validate_workspace
from backend.services.publication import file_identity, owned_file, sync_directory

logger = logging.getLogger("vidgrab.cookie_manager")
COOKIE_LIMIT = 1024 * 1024
OWNERSHIP_LIMIT = 8192


def _field(cookie, key, default):
    value = cookie.get(key, default)
    if not isinstance(value, str) or any(char in value for char in "\0\r\n\t"):
        raise ValueError("Cookie fields must be strings without Netscape row separators")
    return value


def encode_cookies(cookies):
    if not isinstance(cookies, list) or len(cookies) > 4096:
        raise ValueError("Cookie list exceeds its supported size")
    encoded = bytearray(b"# Netscape HTTP Cookie File\n# This file is generated by VidGrab. Do not edit.\n\n")
    for cookie in cookies:
        if not isinstance(cookie, dict):
            raise ValueError("Cookie entries must be objects")
        domain = _field(cookie, "domain", "")
        path = _field(cookie, "path", "/")
        name = _field(cookie, "name", "")
        value = _field(cookie, "value", "")
        expiration = cookie.get("expirationDate")
        if expiration is None:
            expiration = int(time.time()) + 86400 * 30
        if (type(expiration) not in (int, float) or not 0 <= expiration <= 253402300799
                or not math.isfinite(expiration)):
            raise ValueError("Cookie expiration must be a finite, supported timestamp")
        if type(cookie.get("secure", False)) is not bool:
            raise ValueError("Cookie secure flag must be boolean")
        subdomains = "TRUE" if domain.startswith(".") else "FALSE"
        secure = "TRUE" if cookie.get("secure", False) else "FALSE"
        try:
            line = f"{domain}\t{subdomains}\t{path}\t{secure}\t{int(expiration)}\t{name}\t{value}\n".encode("utf-8")
        except UnicodeError as error:
            raise ValueError("Cookie fields must contain valid Unicode") from error
        if len(encoded) + len(line) > COOKIE_LIMIT:
            raise ValueError("Cookie file exceeds its supported size")
        encoded.extend(line)
    return bytes(encoded)


def _private_windows_directory(directory):
    """Protect the newly created directory before any cookie file is opened."""
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    security = ctypes.WinDLL("advapi32", use_last_error=True)
    kernel.GetCurrentProcess.restype = wintypes.HANDLE
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    kernel.LocalFree.argtypes = [ctypes.c_void_p]
    kernel.LocalFree.restype = ctypes.c_void_p
    security.OpenProcessToken.argtypes = [wintypes.HANDLE, wintypes.DWORD, ctypes.POINTER(wintypes.HANDLE)]
    security.OpenProcessToken.restype = wintypes.BOOL
    security.GetTokenInformation.argtypes = [wintypes.HANDLE, ctypes.c_int, ctypes.c_void_p,
                                             wintypes.DWORD, ctypes.POINTER(wintypes.DWORD)]
    security.GetTokenInformation.restype = wintypes.BOOL
    security.ConvertSidToStringSidW.argtypes = [ctypes.c_void_p, ctypes.POINTER(wintypes.LPWSTR)]
    security.ConvertSidToStringSidW.restype = wintypes.BOOL
    security.ConvertStringSecurityDescriptorToSecurityDescriptorW.argtypes = [
        wintypes.LPCWSTR, wintypes.DWORD, ctypes.POINTER(ctypes.c_void_p), ctypes.c_void_p]
    security.ConvertStringSecurityDescriptorToSecurityDescriptorW.restype = wintypes.BOOL
    security.SetFileSecurityW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, ctypes.c_void_p]
    security.SetFileSecurityW.restype = wintypes.BOOL
    token = wintypes.HANDLE()
    sid = wintypes.LPWSTR()
    descriptor = ctypes.c_void_p()
    try:
        if not security.OpenProcessToken(kernel.GetCurrentProcess(), 0x8, ctypes.byref(token)):
            raise ctypes.WinError(ctypes.get_last_error())
        size = wintypes.DWORD()
        security.GetTokenInformation(token, 1, None, 0, ctypes.byref(size))
        if not 0 < size.value <= 65536:
            raise OSError("Cannot verify the cookie directory account")
        user = ctypes.create_string_buffer(size.value)
        if not security.GetTokenInformation(token, 1, user, size, ctypes.byref(size)):
            raise ctypes.WinError(ctypes.get_last_error())
        user_sid = ctypes.cast(user, ctypes.POINTER(ctypes.c_void_p))[0]
        if not security.ConvertSidToStringSidW(user_sid, ctypes.byref(sid)):
            raise ctypes.WinError(ctypes.get_last_error())
        sddl = f"D:P(A;OICI;FA;;;SY)(A;OICI;FA;;;{sid.value})"
        if not security.ConvertStringSecurityDescriptorToSecurityDescriptorW(sddl, 1, ctypes.byref(descriptor), None):
            raise ctypes.WinError(ctypes.get_last_error())
        if not security.SetFileSecurityW(str(directory), 0x80000004, descriptor):
            raise ctypes.WinError(ctypes.get_last_error())
    finally:
        if descriptor.value:
            kernel.LocalFree(descriptor)
        if sid:
            kernel.LocalFree(ctypes.cast(sid, ctypes.c_void_p))
        if token.value:
            kernel.CloseHandle(token)


def _directory_identity(path):
    metadata = path.lstat()
    if is_link(path) or not stat.S_ISDIR(metadata.st_mode):
        raise OutputPathError("Cookie directories must not contain links or reparse points")
    return file_identity(metadata)


def _paths(runtime, attempt, cookie_id):
    try:
        if str(UUID(attempt.id)) != attempt.id:
            raise ValueError
    except (TypeError, ValueError, AttributeError) as error:
        raise OutputPathError("Cookie workspace requires a canonical attempt UUID") from error
    workspace = runtime.data_dir / "attempts" / attempt.id
    if attempt.workspace != workspace:
        raise OutputPathError("Cookie workspace does not match its attempt")
    metadata = workspace / ".vidgrab"
    directory = metadata / ("cookies-" + cookie_id)
    directories = [runtime.data_dir, workspace.parent, workspace, metadata, directory]
    return directory / "cookies.txt", directory / "cookies.witness", directories


def validate_cookie_record(runtime, attempt, ownership):
    """Validate metadata literally, without following or reading filesystem paths."""
    if isinstance(ownership, str):
        if len(ownership.encode("utf-8")) > OWNERSHIP_LIMIT:
            raise OutputPathError("Cookie ownership record exceeds its supported size")
        try:
            ownership = json.loads(ownership)
        except (TypeError, ValueError) as error:
            raise OutputPathError("Cookie ownership record is invalid") from error
    fields = {"version", "cookie_id", "attempt_id", "owner_id", "path", "witness", "directories", "identity"}
    if (not isinstance(ownership, dict) or set(ownership) != fields
            or type(ownership["version"]) is not int or ownership["version"] != 1
            or ownership["attempt_id"] != attempt.id or ownership["owner_id"] != attempt.owner_id):
        raise OutputPathError("Cookie ownership record does not match its attempt owner")
    try:
        if str(UUID(ownership["cookie_id"])) != ownership["cookie_id"]:
            raise ValueError
    except (TypeError, ValueError, AttributeError) as error:
        raise OutputPathError("Cookie ownership nonce is invalid") from error
    path, witness, directories = _paths(runtime, attempt, ownership["cookie_id"])
    if ownership["path"] != str(path) or ownership["witness"] != str(witness):
        raise OutputPathError("Cookie ownership selects a foreign file")
    records = ownership["directories"]
    if (not isinstance(records, list) or len(records) != len(directories)
            or any(not isinstance(record, dict) or set(record) != {"path", "identity"}
                   or record["path"] != str(expected) for record, expected in zip(records, directories))):
        raise OutputPathError("Cookie ownership selects a foreign directory")
    for identity in [ownership["identity"], *(record["identity"] for record in records)]:
        if (not isinstance(identity, dict) or set(identity) != {"device", "inode"}
                or any(type(value) is not int or value < 0 for value in identity.values()) or identity["inode"] == 0):
            raise OutputPathError("Cookie ownership has an invalid file identity")
    return ownership


def verify_cookie_file(runtime, attempt, ownership, *, cleanup=False):
    ownership = validate_cookie_record(runtime, attempt, ownership)
    for record in ownership["directories"]:
        if _directory_identity(Path(record["path"])) != record["identity"]:
            raise OutputPathError("Cookie directory ownership changed; files retained")
    path, witness = Path(ownership["path"]), Path(ownership["witness"])
    present, retained = os.path.lexists(path), os.path.lexists(witness)
    if not cleanup and not (present and retained):
        raise OutputPathError("Cookie delivery requires both owned file names")
    if present and not retained:
        raise OutputPathError("Cookie ownership witness is missing; files retained")
    expected_links = 2 if present and retained else 1
    for selected, exists in ((path, present), (witness, retained)):
        if exists:
            with owned_file(selected, ownership["identity"]) as file:
                if os.fstat(file.fileno()).st_nlink != expected_links:
                    raise OutputPathError("Cookie file has a foreign hard link; files retained")
    return ownership


def _write_cookie_bytes(file, encoded):
    file.write(encoded)
    file.flush()
    os.fsync(file.fileno())


def create_cookie_file(cookies, runtime, attempt):
    """Commit identities for two empty names before writing any credentials."""
    if not cookies:
        return None
    encoded = encode_cookies(cookies)
    validate_workspace(runtime, str(attempt.workspace))
    cookie_id = str(uuid4())
    path, witness, directories = _paths(runtime, attempt, cookie_id)
    for directory in (runtime.data_dir, *runtime.data_dir.parents, *directories[1:-2]):
        _directory_identity(directory)
    directories[-2].mkdir(mode=0o700, exist_ok=True)
    _directory_identity(directories[-2])
    directories[-1].mkdir(mode=0o700)
    if sys.platform == "win32":
        _private_windows_directory(directories[-1])
    directory_records = [{"path": str(directory), "identity": _directory_identity(directory)} for directory in directories]
    flags = os.O_RDWR | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0)
    with os.fdopen(os.open(path, flags, 0o600), "wb") as file:
        os.set_inheritable(file.fileno(), False)
        metadata = os.fstat(file.fileno())
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
            raise OutputPathError("New cookie file is not an exclusive regular file")
        os.link(path, witness, follow_symlinks=False)
        ownership = {"version": 1, "cookie_id": cookie_id, "attempt_id": attempt.id, "owner_id": attempt.owner_id,
                     "path": str(path), "witness": str(witness), "directories": directory_records,
                     "identity": file_identity(metadata)}
        verify_cookie_file(runtime, attempt, ownership)
        os.fsync(file.fileno())
        for directory in reversed(directories):
            sync_directory(directory)
        from backend.db.cookies import register_cookie, mark_cookie_ready
        register_cookie(runtime, attempt, ownership)
        _write_cookie_bytes(file, encoded)
    mark_cookie_ready(runtime, attempt, ownership)
    logger.info("Wrote forwarded cookies for attempt %s", attempt.id)
    return str(path)


def cleanup_cookie_file(runtime, attempt, ownership):
    """Call only after every durable runtime/worker fence and joined tree exit."""
    ownership = verify_cookie_file(runtime, attempt, ownership, cleanup=True)
    path, witness = Path(ownership["path"]), Path(ownership["witness"])
    if os.path.lexists(path):
        path.unlink()
        sync_directory(path.parent)
    if os.path.lexists(witness):
        with owned_file(witness, ownership["identity"], unshared=True):
            pass
        witness.unlink()
        sync_directory(witness.parent)
