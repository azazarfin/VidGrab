"""Deterministic schema and TS/classic-JS/Rust outputs; never starts the app."""

import argparse
import json
from pathlib import Path

from backend.api.models import contract_schema

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "packages/protocol"


def typescript_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    for keyword in ("anyOf", "oneOf"):
        if keyword in schema:
            return " | ".join(typescript_type(item) for item in schema[keyword])
    kind = schema.get("type")
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind == "array":
        return "Array<" + typescript_type(schema["items"]) + ">"
    if kind == "object":
        properties = schema.get("properties")
        if properties is not None:
            required = schema.get("required", [])
            fields = [json.dumps(name) + ("" if name in required else "?") + ": " + typescript_type(value)
                      for name, value in properties.items()]
            return "{ " + "; ".join(fields) + " }"
        return "Record<string, " + typescript_type(schema.get("additionalProperties", {})) + ">"
    return "unknown"


def outputs():
    schema = contract_schema()
    schemas = [schema["request"], schema["response"]]
    for operation in schema["operations"].values():
        schemas.extend([operation["params"], operation["result"]])
    definitions = {}
    for item in schemas:
        for name, definition in item.get("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError("Conflicting generated definition: " + name)
            definitions[name] = definition
        if "title" in item and "type" in item:
            definitions[item["title"]] = {key: value for key, value in item.items() if key != "$defs"}
    types = ["// Generated by packages.protocol.generate; edit Pydantic models and regenerate."]
    types.extend("export type " + name + " = " + typescript_type(value) + ";" for name, value in sorted(definitions.items()))
    types.append("export interface Operations {")
    for name, operation in schema["operations"].items():
        types.append("  " + json.dumps(name) + ": { params: " + operation["params"]["title"]
                     + "; result: " + operation["result"]["title"] + " };")
    types.extend([
        "}",
        "export interface RequestOptions { request_id: string; idempotency_key?: string }",
        "export type Transport = (request: Request) => Promise<unknown>;",
        "export interface Client { request<K extends keyof Operations>(operation: K, params: Operations[K]['params'], options: RequestOptions): Promise<Operations[K]['result']> }",
        "export type MutationOperation = 'settings.patch' | 'downloads.enqueue' | 'downloads.action' | 'downloads.authenticate';",
        "export interface PendingMutation { readonly operation: MutationOperation; readonly params: unknown; readonly key: string }",
        "export interface ControlState { connected: boolean; capabilities: Capabilities | null; snapshot: Snapshot | null; has_more: boolean }",
        "export interface ControlSession { readonly state: ControlState; readonly pending: PendingMutation | null; sync(force?: boolean): Promise<ControlState>; loadMore(): Promise<ControlState>; read<K extends keyof Operations>(operation: K, params?: Operations[K]['params']): Promise<Operations[K]['result']>; mutate<K extends MutationOperation>(operation: K, params: Operations[K]['params']): Promise<Operations[K]['result']>; replay(): Promise<Operations[MutationOperation]['result']>; dismiss(key: string): void }",
        "export { createClient, createSession, ProtocolError } from './client.mjs';",
    ])
    runtime = (PACKAGE / "client-runtime.js").read_text(encoding="utf-8")
    runtime += "\n" + (PACKAGE / "session-runtime.js").read_text(encoding="utf-8")
    embedded = "const contract = " + json.dumps(schema, ensure_ascii=True, separators=(",", ":"), sort_keys=True) + ";\n"
    module = "// Generated by packages.protocol.generate.\n" + embedded + runtime + "\nexport const createClient = transport => makeClient(transport, contract);\n"
    classic = "// Generated by packages.protocol.generate.\n(function (global) {\n" + embedded + runtime.replace("export ", "")
    classic += "\nglobal.vidGrabProtocol = { createClient: transport => makeClient(transport, contract), createSession, ProtocolError, validateRequest: request => validateRequest(request, contract), isMutation: operation => contract.operations[operation]?.mutation === true };\n})(globalThis);\n"
    declaration = """// Generated by packages.protocol.generate.
import type { Client, ControlSession, Request, Transport } from './client';
export declare function createClient(transport: Transport): Client;
export declare function createSession(client: Client, identify: () => string): ControlSession;
export declare class ProtocolError extends Error {
  code: string;
  request_id: string | null;
  retryable: boolean;
  retry_at: number | null;
  provenance: string;
  details: Record<string, unknown>;
}
"""
    rust = "// Generated by packages.protocol.generate.\npub const OPERATIONS: &[(&str, bool)] = &[\n"
    rust += "".join("    (" + json.dumps(name) + ", " + str(item["mutation"]).lower() + "),\n" for name, item in schema["operations"].items())
    rust += "];\npub const VERSION: u64 = 1;\n"
    return {
        PACKAGE / "schema-v1.json": json.dumps(schema, ensure_ascii=True, indent=2, sort_keys=True) + "\n",
        PACKAGE / "generated/client.ts": "\n".join(types) + "\n",
        PACKAGE / "generated/client.mjs": module,
        PACKAGE / "generated/client.d.mts": declaration,
        PACKAGE / "generated/client.js": classic,
        PACKAGE / "generated/operations.rs": rust,
        ROOT / "extension/lib/protocol.js": classic,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Refuse stale generated files without writing")
    arguments = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if arguments.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale protocol outputs: " + ", ".join(stale))
    print("Protocol outputs are current" if arguments.check else "Generated schema and TS/JS/Rust clients")


if __name__ == "__main__":
    main()
